#!/usr/bin/env python3
"""Generate the Java SE API javadoc served at /Java{N}/ from OpenJDK's sources.

Each version is documented from the src.zip of a Zulu (OpenJDK) build, with
that JDK's own javadoc tool, so the result matches the official API docs'
layout (/Java21/java.base/java/lang/String.html; flat /Java8/java/lang/...).
OpenJDK's sources, and so this output, are GPLv2 with the Classpath Exception.

The JDK is located (downloaded if needed) via jgo, so run this in an
environment that has it, e.g.:

    sudo -u cronbot env UV_CACHE_DIR=/var/www/javadoc/cache/uv \
      uv run --project /var/www/javadoc/src/pombast \
      python .tools/jdk-javadoc.py -o /var/www/javadoc/build 21

Output goes to {OUT}/Java{N}/, staged beside it and swapped in whole.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

NOTICE = (
    "Generated by SciJava from the sources of OpenJDK {v} (Zulu), which are "
    "licensed under the <a href='https://openjdk.org/legal/gplv2+ce.html'>GNU "
    "General Public License, version 2, with the Classpath Exception</a>. "
    "Java and OpenJDK are trademarks or registered trademarks of Oracle and/or "
    "its affiliates."
)
# Java 8's public API: the packages its official docs cover.
JAVA8_PACKAGES = "java:javax:org.ietf.jgss:org.omg:org.w3c.dom:org.xml.sax"


def java_home(version: int) -> Path:
    # The site's JDK cache (see update.py), unless told otherwise.
    os.environ.setdefault("CJDK_CACHE_DIR", "/var/www/javadoc/cache/cjdk")
    from jgo.util.java import JavaLocator, JavaSource

    exe = JavaLocator(java_version=version, java_source=JavaSource.DOWNLOAD).locate()
    return exe.parent.parent


def src_zip(home: Path) -> Path:
    for p in (home / "lib" / "src.zip", home / "src.zip"):
        if p.is_file():
            return p
    raise SystemExit(f"No src.zip in {home}")


def javadoc_args(version: int, src: Path, dest: Path) -> list[str]:
    title = f"Java SE {version} &amp; JDK {version} API"
    args = [
        "-d", str(dest),
        "-encoding", "UTF-8", "-docencoding", "UTF-8", "-charset", "UTF-8",
        "-quiet", "-notimestamp", "-use", "-Xdoclint:none",
        "-windowtitle", f"Java SE {version} & JDK {version} API",
        "-doctitle", title,
        "-bottom", NOTICE.format(v=version),
    ]  # fmt: skip
    if version == 8:
        return args + ["-sourcepath", str(src), "-subpackages", JAVA8_PACKAGES]
    modules = sorted(
        d.name
        for d in src.iterdir()
        if d.is_dir()
        and (d.name.startswith("java.") or d.name.startswith("jdk."))
        # Not public API (the official docs omit these too).
        and not d.name.startswith(("jdk.internal.", "jdk.unsupported"))
        and d.name != "jdk.hotspot.agent"
    )
    return args + [
        "--module-source-path", str(src),
        "--module", ",".join(modules),
        "--system", "none",
    ]


def _quote(arg: str) -> str:
    """Quote one @argfile argument (backslashes and double quotes escaped)."""
    return '"' + arg.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(version: int, out: Path) -> None:
    home = java_home(version)
    javadoc = home / "bin" / "javadoc"
    dest = out / f"Java{version}"
    staged = out / f".Java{version}.staging"
    shutil.rmtree(staged, ignore_errors=True)
    with tempfile.TemporaryDirectory(prefix=f"jdk{version}-src-", dir=out) as tmp:
        src = Path(tmp) / "src"
        print(f"Java {version}: extracting {src_zip(home)}", flush=True)
        with zipfile.ZipFile(src_zip(home)) as z:
            z.extractall(src)
        argfile = Path(tmp) / "args"
        argfile.write_text(
            "\n".join(_quote(a) for a in javadoc_args(version, src, staged)) + "\n"
        )
        print(f"Java {version}: running {javadoc}", flush=True)
        proc = subprocess.run(
            # -J options cannot go in an @argfile.
            [str(javadoc), "-J-Xmx6g", f"@{argfile}"],
            capture_output=True,
            text=True,
            errors="replace",
        )
    # javadoc reports errors in a few internal sources, outside the documented
    # API; keep its output for reference.
    log = out / f".Java{version}.javadoc.log"
    log.write_text(proc.stdout + proc.stderr)
    if not (staged / "index.html").is_file():
        tail = "\n".join((proc.stderr or proc.stdout).splitlines()[-15:])
        raise SystemExit(f"Java {version}: javadoc exited {proc.returncode}:\n{tail}")
    # Swap the new docs in whole, never modifying files in place: published
    # snapshots hard-link to these.
    old = out / f".Java{version}.old"
    if dest.exists():
        os.rename(dest, old)
    os.rename(staged, dest)
    shutil.rmtree(old, ignore_errors=True)
    n = sum(1 for _ in dest.rglob("*.html"))
    print(f"Java {version}: {n} pages in {dest} (javadoc exit {proc.returncode})")
    if version == MODULE_MAP_VERSION:
        write_module_map(dest / "element-list", out / MODULE_MAP)


# Java 9 and 10's docs, which the site redirects to Java 11's, are not yet
# module-nested (/Java10/java/lang/String.html), so redirecting needs each
# package's module: a RewriteMap of package dir -> module, e.g. "java/lang
# java.base", from Java 11's element-list.
MODULE_MAP = "jdk-modules.map"
MODULE_MAP_VERSION = 11


def write_module_map(element_list: Path, dest: Path) -> None:
    rows, module = [], None
    for line in element_list.read_text().splitlines():
        if line.startswith("module:"):
            module = line[len("module:") :]
        elif line and module:
            rows.append(f"{line.replace('.', '/')} {module}\n")
    tmp = dest.with_name(f".{dest.name}.tmp")
    tmp.write_text("".join(sorted(rows)))
    os.replace(tmp, dest)
    print(f"Wrote {len(rows)} package modules to {dest}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--out", type=Path, required=True, help="site build tree")
    ap.add_argument("versions", type=int, nargs="+", help="Java versions, e.g. 8 11 17")
    args = ap.parse_args()
    for v in args.versions:
        generate(v, args.out)


if __name__ == "__main__":
    sys.exit(main())
